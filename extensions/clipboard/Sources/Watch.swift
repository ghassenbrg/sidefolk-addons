import AppKit
import Foundation

/// The clipboard, looked at twice a second (macOS has no notification for it): a new copy goes into the history,
/// unless an app marked it concealed or passing (password managers do, nspasteboard.org), or Sidefolk put it there.
@MainActor
final class Watch {
    let history: History
    private let board = NSPasteboard.general
    private var seen: Int
    /// The change count after Sidefolk's own writes, which aren't new copies.
    private var ours: Int?

    static let skipped: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
                                       "com.agilebits.onepassword", "com.typeit4me.clipping", "de.petermaurer.TransientPasteboardType",
                                       "Pasteboard generator type", "net.antelle.keeweb"]
    static let maxImageBytes = 20 * 1024 * 1024

    init(history: History) {
        self.history = history
        seen = NSPasteboard.general.changeCount
    }

    func run() async {
        while !Task.isCancelled {
            check()
            if history.expireSecrets() {}
            try? await Task.sleep(for: .milliseconds(500))
        }
    }

    func check(now: Date = Date()) {
        let count = board.changeCount
        guard count != seen else { return }
        seen = count
        if count == ours { return }
        guard history.isKeeping(now: now), let entry = read(now: now) else { return }
        history.add(entry)
    }

    private func read(now: Date) -> Entry? {
        let types = Set((board.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skipped) else { return nil }
        // Which app was in front isn't knowable here: the sandbox keeps Launch Services closed, since it could also
        // open apps and links. Some apps name themselves on the clipboard (nspasteboard.org); that is all we use.
        let source = board.string(forType: NSPasteboard.PasteboardType("org.nspasteboard.source")).flatMap(Self.appName)
        if let urls = board.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let paths = urls.map(\.path)
            return Entry(id: UUID().uuidString, kind: .file, text: paths.joined(separator: "\n"), files: paths, source: source, copied: now)
        }
        if let text = board.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let secret = history.options.hideSecrets && Recognize.isSecret(text)
            // Formatting is kept for text that has some, up to a size worth keeping.
            let rtf = board.data(forType: .rtf).flatMap { $0.count <= 512 * 1024 ? $0 : nil }
            return Entry(id: UUID().uuidString, kind: Recognize.kind(text), text: String(text.prefix(200_000)), rtf: secret ? nil : rtf,
                         source: source, copied: now, secret: secret)
        }
        if types.contains(NSPasteboard.PasteboardType.png.rawValue) || types.contains(NSPasteboard.PasteboardType.tiff.rawValue),
           let image = NSImage(pasteboard: board), let tiff = image.tiffRepresentation, let rep = NSBitmapImageRep(data: tiff),
           let png = rep.representation(using: .png, properties: [:]), png.count <= Self.maxImageBytes, let name = history.storeImage(png) {
            return Entry(id: UUID().uuidString, kind: .image, image: name, width: rep.pixelsWide, height: rep.pixelsHigh, source: source, copied: now)
        }
        return nil
    }

    /// "com.apple.Safari" → "Safari": the last part of a bundle id, which is the app's name often enough to help.
    static func appName(_ bundle: String) -> String? {
        let last = bundle.split(separator: ".").last.map(String.init) ?? bundle
        return last.isEmpty ? nil : last.prefix(1).uppercased() + last.dropFirst()
    }

    /// Puts a copy back on the clipboard, with its formatting unless `plain`.
    func write(_ e: Entry, plain: Bool) {
        board.clearContents()
        switch e.kind {
        case .file:
            board.writeObjects((e.files ?? []).map { URL(fileURLWithPath: $0) as NSURL })
        case .image:
            if let data = history.imageData(e) {
                board.setData(data, forType: .png)
                if let tiff = NSImage(data: data)?.tiffRepresentation { board.setData(tiff, forType: .tiff) }
            }
        case .link:
            board.setString(e.text ?? "", forType: .string)
            if !plain { board.setString(e.text ?? "", forType: .URL) }
        case .text, .color, .code:
            board.setString(e.text ?? "", forType: .string)
            if !plain, let rtf = e.rtf { board.setData(rtf, forType: .rtf) }
        }
        ours = board.changeCount
        seen = ours ?? seen
    }
}
