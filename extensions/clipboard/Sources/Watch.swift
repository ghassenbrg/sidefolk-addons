import AppKit
import Foundation

/// The clipboard, looked at twice a second (macOS has no notification for it, Maccy does the same): a new copy goes into
/// the history, unless an app marked it concealed or passing (password managers do, nspasteboard.org), Sidefolk put it
/// there, or the person's rules leave it out (an app, a kind, a pattern, "skip the next one").
@MainActor
final class Watch {
    let history: History
    let source: Source
    private let board: NSPasteboard
    private var seen: Int
    /// The change count after Sidefolk's own writes, which aren't new copies.
    private var ours: Int?

    /// Always left out: what password managers and generators mark (Maccy leaves out the same).
    static let skipped: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
                                       "com.agilebits.onepassword", "com.typeit4me.clipping", "de.petermaurer.TransientPasteboardType",
                                       "Pasteboard generator type", "net.antelle.keeweb"]
    /// Formatting worth keeping is rarely bigger; a whole web page's HTML isn't kept.
    static let maxRich = 512 * 1024
    static let html = NSPasteboard.PasteboardType.html
    static let heic = NSPasteboard.PasteboardType("public.heic"), jpeg = NSPasteboard.PasteboardType("public.jpeg")

    init(history: History, source: Source, board: NSPasteboard = .general) {
        self.history = history
        self.source = source
        self.board = board
        seen = board.changeCount
    }

    func run() async {
        while !Task.isCancelled {
            await check()
            history.expireSecrets()
            try? await Task.sleep(for: .milliseconds(500))
        }
    }

    func check(now: Date = Date()) async {
        let count = board.changeCount
        guard count != seen else { return }
        seen = count
        if count == ours { return }
        guard history.isKeeping(now: now) else { return }
        if history.options.skipNext {
            history.set { $0.skipNext = false }
            return
        }
        let types = Set((board.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skipped), types.isDisjoint(with: history.options.ignoredTypes) else { return }
        guard var copy = read(now: now) else { return }
        // Which app it came from: the app may name itself on the clipboard; otherwise Sidefolk says which was in front.
        let named = board.string(forType: NSPasteboard.PasteboardType("org.nspasteboard.source"))
        let front = await source.ask(change: count)
        copy.entry.app = named ?? front?.app
        copy.entry.source = front?.name ?? named.flatMap(Self.appName)
        let options = history.options
        if options.ignores(app: copy.entry.app, name: copy.entry.source) { return }
        if let text = copy.entry.text, copy.entry.kind != .file, options.ignores(text: text) { return }
        history.add(copy.entry, files: copy.files)
    }

    /// A copy and the files it brings, not yet written.
    struct Copy {
        var entry: Entry
        var files: [String: Data] = [:]
    }

    /// What is on the clipboard now, as one copy: files first (Finder also puts their names as text), then text with
    /// its formatting, then a picture.
    func read(now: Date) -> Copy? {
        let options = history.options
        let id = UUID().uuidString
        let types = board.types ?? []
        if let urls = board.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            guard options.keepFiles else { return nil }
            let paths = urls.map(\.path)
            var copy = Copy(entry: Entry(id: id, kind: .file, text: paths.joined(separator: "\n"), files: paths, copied: now, first: now))
            // Finder puts the file's icon or a preview beside it; the sandbox can't open the file itself to make one.
            if let picture = pictureData(types), let thumb = Pictures.thumbnail(picture.data) {
                copy.entry.thumb = "thumbs/\(id).png"
                copy.files[copy.entry.thumb!] = thumb
            }
            return copy
        }
        if let text = board.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let secret = options.hideSecrets && Recognize.isSecret(text)
            var copy = Copy(entry: Entry(id: id, kind: Recognize.kind(text), text: String(text.prefix(200_000)), copied: now, first: now, secret: secret))
            // Secrets stay in memory only: no formatting file for them.
            if !secret && options.keepFormatting {
                if let rtf = board.data(forType: .rtf), rtf.count <= Self.maxRich {
                    copy.entry.rtfFile = "rich/\(id).rtf"
                    copy.files[copy.entry.rtfFile!] = rtf
                }
                if let html = board.data(forType: Self.html), html.count <= Self.maxRich {
                    copy.entry.htmlFile = "rich/\(id).html"
                    copy.files[copy.entry.htmlFile!] = html
                }
            }
            return copy
        }
        guard options.keepImages, let found = pictureData(types), let picture = Pictures.picture(found.data, isPNG: found.png) else { return nil }
        var copy = Copy(entry: Entry(id: id, kind: .image, image: "images/\(id).png", width: picture.width, height: picture.height,
                                     bytes: picture.png.count, digest: picture.digest, copied: now, first: now))
        copy.files[copy.entry.image!] = picture.png
        if let thumb = Pictures.thumbnail(picture.png) {
            copy.entry.thumb = "thumbs/\(id).png"
            copy.files[copy.entry.thumb!] = thumb
        }
        return copy
    }

    /// The picture on the clipboard, in the first of the formats apps use (screenshots put PNG and TIFF).
    private func pictureData(_ types: [NSPasteboard.PasteboardType]) -> (data: Data, png: Bool)? {
        for type in [NSPasteboard.PasteboardType.png, .tiff, Self.heic, Self.jpeg] where types.contains(type) {
            if let data = board.data(forType: type) { return (data, type == .png) }
        }
        return nil
    }

    /// "com.apple.Safari" → "Safari": the last part of a bundle id, which is the app's name often enough to help.
    static func appName(_ bundle: String) -> String? {
        let last = bundle.split(separator: ".").last.map(String.init) ?? bundle
        return last.isEmpty ? nil : last.prefix(1).uppercased() + last.dropFirst()
    }

    /// Puts a copy back on the clipboard, with its formatting unless `plain`.
    func write(_ e: Entry, plain: Bool) {
        board.clearContents()
        switch e.kind {
        case .file:
            board.writeObjects((e.files ?? []).map { URL(fileURLWithPath: $0) as NSURL })
        case .image:
            if let data = history.data(e.image) {
                board.setData(data, forType: .png)
                if let tiff = NSImage(data: data)?.tiffRepresentation { board.setData(tiff, forType: .tiff) }
            }
        case .link:
            board.setString(e.text ?? "", forType: .string)
            if !plain { board.setString(e.text ?? "", forType: .URL) }
        case .text, .color, .code:
            board.setString(e.text ?? "", forType: .string)
            if !plain {
                if let rtf = history.data(e.rtfFile) { board.setData(rtf, forType: .rtf) }
                if let html = history.data(e.htmlFile) { board.setData(html, forType: Self.html) }
            }
        }
        ours = board.changeCount
        seen = ours ?? seen
    }
}

/// Which app was in front for a copy (D68): the sandbox keeps Launch Services closed (it could also open apps and
/// links, D63), so the extension asks Sidefolk with `sidefolk/clipboard.source`, and Sidefolk answers once per change of
/// the clipboard with the app's bundle id and name.
@MainActor
final class Source {
    struct App: Equatable {
        var app: String?
        var name: String?
    }

    private let send: () -> Void
    private var waiting: (change: Int, done: CheckedContinuation<App?, Never>)?
    /// How long a copy waits for Sidefolk: it answers in a few milliseconds while it runs.
    static let patience: Duration = .milliseconds(400)

    init(send: @escaping () -> Void) {
        self.send = send
    }

    func ask(change: Int) async -> App? {
        finish(nil)
        return await withCheckedContinuation { done in
            waiting = (change, done)
            send()
            Task {
                try? await Task.sleep(for: Self.patience)
                if self.waiting?.change == change { self.finish(nil) }
            }
        }
    }

    /// Sidefolk's answer; one for an earlier change is old news.
    func receive(change: Int?, app: String?, name: String?) {
        guard let waiting, change == nil || change == waiting.change else { return }
        finish(App(app: app, name: name))
    }

    private func finish(_ app: App?) {
        let done = waiting?.done
        waiting = nil
        done?.resume(returning: app)
    }
}
